CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE thalion.organization (
    org_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    business_timezone text NOT NULL CHECK (btrim(business_timezone) <> ''),
    config_revision bigint NOT NULL DEFAULT 1 CHECK (config_revision > 0),
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE FUNCTION thalion.check_business_timezone() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, thalion AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_timezone_names
        WHERE name = NEW.business_timezone
    ) THEN
        RAISE EXCEPTION 'unknown business timezone' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER organization_timezone
BEFORE INSERT OR UPDATE OF business_timezone ON thalion.organization
FOR EACH ROW EXECUTE FUNCTION thalion.check_business_timezone();

CREATE TABLE thalion.principal (
    principal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL REFERENCES thalion.organization (org_id),
    identity_type text GENERATED ALWAYS AS ('principal'::text) STORED,
    principal_type text NOT NULL CHECK (principal_type IN ('employee', 'group', 'service')),
    authority_issuer text NOT NULL CHECK (btrim(authority_issuer) <> ''),
    authority_subject_key text NOT NULL CHECK (btrim(authority_subject_key) <> ''),
    disabled boolean NOT NULL DEFAULT false,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (org_id, principal_id),
    UNIQUE (authority_issuer, authority_subject_key)
);

CREATE TABLE thalion.space (
    space_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL REFERENCES thalion.organization (org_id),
    identity_type text GENERATED ALWAYS AS ('space'::text) STORED,
    name text NOT NULL CHECK (btrim(name) <> ''),
    classification text NOT NULL CHECK (btrim(classification) <> ''),
    owner_principal_id bigint NOT NULL,
    lifecycle text NOT NULL DEFAULT 'active' CHECK (lifecycle IN ('active', 'archived')),
    row_generation bigint NOT NULL DEFAULT 1 CHECK (row_generation > 0),
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (org_id, space_id),
    FOREIGN KEY (org_id, owner_principal_id)
        REFERENCES thalion.principal (org_id, principal_id)
);

CREATE TABLE thalion.object_identity (
    object_type text NOT NULL CHECK (object_type IN ('principal', 'space')),
    object_id bigint NOT NULL CHECK (object_id > 0),
    org_id bigint NOT NULL REFERENCES thalion.organization (org_id),
    space_id bigint,
    public_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (object_type, object_id),
    UNIQUE (org_id, object_type, object_id),
    FOREIGN KEY (org_id, space_id) REFERENCES thalion.space (org_id, space_id)
        DEFERRABLE INITIALLY DEFERRED,
    CHECK (
        (object_type = 'principal' AND space_id IS NULL)
        OR (object_type = 'space' AND space_id IS NOT NULL AND space_id = object_id)
    )
);

ALTER TABLE thalion.principal ADD CONSTRAINT principal_registered_identity
FOREIGN KEY (org_id, identity_type, principal_id)
    REFERENCES thalion.object_identity (org_id, object_type, object_id)
    DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE thalion.space ADD CONSTRAINT space_registered_identity
FOREIGN KEY (org_id, identity_type, space_id)
    REFERENCES thalion.object_identity (org_id, object_type, object_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE FUNCTION thalion.reject_identity_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, thalion AS $$
BEGIN
    RAISE EXCEPTION 'registered public identity is immutable'
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER identity_immutable
BEFORE UPDATE OR DELETE ON thalion.object_identity
FOR EACH ROW EXECUTE FUNCTION thalion.reject_identity_change();

CREATE FUNCTION thalion.verify_identity_entity() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, thalion AS $$
DECLARE
    target_type text;
    target_id bigint;
    target_org bigint;
    entity_exists boolean;
BEGIN
    IF TG_TABLE_NAME = 'object_identity' THEN
        target_type := NEW.object_type;
        target_id := NEW.object_id;
        target_org := NEW.org_id;
    ELSIF TG_TABLE_NAME = 'principal' THEN
        target_type := 'principal';
        target_id := OLD.principal_id;
        target_org := OLD.org_id;
    ELSE
        target_type := 'space';
        target_id := OLD.space_id;
        target_org := OLD.org_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM thalion.object_identity
        WHERE object_type = target_type AND object_id = target_id
          AND org_id = target_org
    ) THEN
        RETURN NULL;
    END IF;

    IF target_type = 'principal' THEN
        SELECT EXISTS (
            SELECT 1 FROM thalion.principal
            WHERE principal_id = target_id AND org_id = target_org
        ) INTO entity_exists;
    ELSE
        SELECT EXISTS (
            SELECT 1 FROM thalion.space
            WHERE space_id = target_id AND org_id = target_org
        ) INTO entity_exists;
    END IF;

    IF NOT entity_exists THEN
        RAISE EXCEPTION 'registered identity requires matching entity'
            USING ERRCODE = '23503';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER identity_entity_exists
AFTER INSERT ON thalion.object_identity DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION thalion.verify_identity_entity();

CREATE CONSTRAINT TRIGGER principal_identity_survives
AFTER DELETE ON thalion.principal DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION thalion.verify_identity_entity();

CREATE CONSTRAINT TRIGGER space_identity_survives
AFTER DELETE ON thalion.space DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION thalion.verify_identity_entity();
